<?php

namespace App\Services;

use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\Storage;

/**
 * Stores and removes the profile picture on the public disk.
 *
 * The upload flow is deliberately "write new, then swap, then delete old":
 * the currently visible picture keeps working until the replacement is safely
 * stored, and the previous file is only removed once nothing references it.
 */
class ProfileImageService
{
    private const DIRECTORY = 'profile';

    public function __construct(
        private string $disk = 'public',
    ) {}

    /**
     * Store an uploaded picture and return its relative path.
     *
     * The filename is generated by Laravel (random hash + validated
     * extension), so user input never becomes a path.
     */
    public function store(UploadedFile $file): string
    {
        return $file->store(self::DIRECTORY, $this->disk);
    }

    /**
     * Delete a stored picture if it still exists.
     */
    public function delete(?string $path): void
    {
        if (blank($path)) {
            return;
        }

        if (preg_match('#^(https?:)?//#i', $path) === 1 || str_starts_with($path, '/')) {
            return;
        }

        $disk = Storage::disk($this->disk);

        if ($disk->exists($path)) {
            $disk->delete($path);
        }
    }
}
